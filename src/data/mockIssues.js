// Helper to associate reported issues with schematic New Town landmarks
export function matchIssueToBuilding(issue, buildings = SCHEMATIC_BUILDINGS) {
  if (!issue) return null;

  const bldgField = (issue.building || '').toLowerCase();
  const locField = (issue.location || '').toLowerCase();
  const roomField = (issue.floorRoom || '').toLowerCase();
  const hoodField = (issue.neighbourhood || '').toLowerCase();

  // 1. Direct name match
  for (const bldg of buildings) {
    if (bldgField && bldgField === bldg.name.toLowerCase()) {
      return bldg;
    }
    if (locField && locField.includes(bldg.name.toLowerCase())) {
      return bldg;
    }
  }

  // 2. Alias match
  for (const bldg of buildings) {
    for (const alias of bldg.aliases) {
      const lowerAlias = alias.toLowerCase();
      if (
        (bldgField && bldgField.includes(lowerAlias)) ||
        (locField && locField.includes(lowerAlias)) ||
        (roomField && roomField.includes(lowerAlias)) ||
        (hoodField && hoodField.includes(lowerAlias))
      ) {
        return bldg;
      }
    }
  }

  return null;
}

/**
 * Resolves real geographic coordinates for an issue honestly:
 * - Returns exact coordinates if verified and stored on the issue
 * - Returns landmark reference coordinates if matched to a known landmark
 * - Returns null for issues with unverified/unknown locations (sent to Unmapped Reports)
 * - NEVER fabricates random or fictitious GPS coordinates
 */
export function resolveIssueCoordinates(issue) {
  if (!issue) return null;

  // 0. Explicitly unmapped issues or general/unknown location tickets
  if (
    issue.locationPrecision === 'unmapped' ||
    issue.building === 'Other / Unmapped New Town Location'
  ) {
    return null;
  }

  // 1. Exact verified GPS or user-pinned coordinates stored directly on issue
  if (
    issue.coordinates &&
    typeof issue.coordinates.lat === 'number' &&
    typeof issue.coordinates.lng === 'number' &&
    !isNaN(issue.coordinates.lat) &&
    !isNaN(issue.coordinates.lng)
  ) {
    const isExact = issue.locationPrecision === 'verified-gps';
    const isUserPinned = issue.locationPrecision === 'user-pinned';
    return {
      lat: issue.coordinates.lat,
      lng: issue.coordinates.lng,
      isExact: isExact,
      source: isExact
        ? 'Verified GPS Coordinates'
        : isUserPinned
        ? (issue.locationSource || 'User-Pinned Location')
        : (issue.locationSource || 'Approximate Landmark Location'),
    };
  }

  // 2. Matched building from SCHEMATIC_BUILDINGS
  const matchedBldg = matchIssueToBuilding(issue, SCHEMATIC_BUILDINGS);
  if (matchedBldg && matchedBldg.coordinates) {
    return {
      lat: matchedBldg.coordinates.lat,
      lng: matchedBldg.coordinates.lng,
      isExact: false,
      source: `Approximate Landmark Location: ${matchedBldg.name}`,
    };
  }

  // 3. Fallback dictionary check for recognized New Town landmarks
  const combinedText = `${issue.location || ''} ${issue.building || ''} ${issue.floorRoom || ''} ${issue.neighbourhood || ''} ${issue.area || ''}`.toLowerCase();
  for (const [key, val] of Object.entries(NEW_TOWN_LANDMARK_COORDINATES)) {
    if (combinedText.includes(key.toLowerCase())) {
      return {
        lat: val.lat,
        lng: val.lng,
        isExact: false,
        source: `Approximate Landmark Location: ${val.name}`,
      };
    }
  }

  // 4. Honest unmapped fallback
  return null;
}
